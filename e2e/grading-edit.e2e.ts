const raw = "synthetic-copy-raw", ace = "synthetic-copy-ace"

test("raw/graded local drafts keep independent copies, certificates, custom and legacy fields, cancel changes nothing", async ({ page, context }) => {
  const original = await page.getByLabel(`Draft ${ace}`).textContent()
  await page.getByRole("button", { name: `Edit ${raw}`, exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Edit copy grading" })
  await dialog.getByLabel("Grading status").selectOption("graded")
  await dialog.getByRole("combobox", { name: "Provider", exact: true }).selectOption("psa")
  await dialog.getByLabel("Recorded grade", { exact: true }).fill("8.5")
  await dialog.getByLabel("Certificate number", { exact: true }).fill("00001234")
  await expect(dialog.getByRole("link", { name: "View on PSA" })).toHaveAttribute("href", "https://www.psacard.com/cert/00001234/psa")
  await expect(dialog.getByRole("link", { name: "View on PSA" })).toHaveAttribute("rel", "noopener noreferrer")
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByLabel(`Draft ${raw}`)).toContainText('"grading":null')
  await expect(page.getByLabel(`Draft ${ace}`)).toHaveText(original!)
  await page.getByRole("button", { name: `Edit ${raw}`, exact: true }).click()
  await dialog.getByLabel("Grading status").selectOption("graded")
  await dialog.getByRole("combobox", { name: "Provider", exact: true }).selectOption("ace")
  await dialog.getByLabel("Certificate number", { exact: true }).fill("00001234")
  await expect(dialog.getByText(/Possible duplicate provider/)).toBeVisible()
  await dialog.getByRole("combobox", { name: "Provider", exact: true }).selectOption("custom")
  const long = "SyntheticCustomProvider".repeat(15)
  await dialog.getByLabel("Custom provider name").fill(long)
  await dialog.getByLabel("Recorded grade", { exact: true }).fill("Authentic, legacy text")
  await dialog.getByLabel("Scale / version").fill("Synthetic historical scale")
  await dialog.getByLabel("Designation / qualifier").fill("OC")
  await dialog.getByLabel("Holder / version").fill("Legacy holder v1")
  await dialog.getByLabel("Label variant / custom style").fill("Synthetic custom label".repeat(15))
  await dialog.getByRole("button", { name: "Add subgrade", exact: true }).click()
  await dialog.getByLabel("Subgrade name", { exact: true }).fill("Corners")
  await dialog.getByLabel("Subgrade value", { exact: true }).fill("9.5")
  await context.setOffline(true)
  await dialog.getByRole("button", { name: "Use grading draft", exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const updated = JSON.parse((await page.getByLabel(`Draft ${raw}`).textContent())!)
  expect(updated.grading.certificate).toBe("00001234")
  expect(updated.grading.provider.name).toBe(long)
  expect(updated.grading.subgrades).toEqual([{ name: "Corners", grade: "9.5" }])
  expect(updated.acquiredAt).toBe("2026-01-01T00:00:00Z")
  expect(updated.version).toBe(2)
  await expect(page.getByLabel(`Draft ${ace}`)).toHaveText(original!)
  await expect(page.getByLabel("Grading harness notice")).toContainText("not persisted")
  await page.getByRole("button", { name: `Edit ${raw}`, exact: true }).click()
  await expect(dialog.getByLabel("Recorded grade", { exact: true })).toHaveValue("Authentic, legacy text")
  await dialog.getByLabel("Grading status").selectOption("raw")
  await dialog.getByRole("button", { name: "Use grading draft", exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByLabel(`Draft ${raw}`)).toContainText('"grading":null')
  await expect(page.getByLabel(`Draft ${raw}`)).toContainText('"id":"synthetic-copy-raw"')
})

test("safe local URL parsing, provider mismatch and lookup fallback, no provider fetch", async ({ page }) => {
  const outbound: string[] = []
  page.on("request", req => { if (/psacard|acegrading|cgccards|beckett/.test(req.url())) outbound.push(req.url()) })
  await page.getByRole("button", { name: `Edit ${ace}`, exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Edit copy grading" })
  await expect(dialog.getByRole("link", { name: "Open ACE lookup page" })).toHaveAttribute("href", "https://acegrading.com/cert")
  await expect(dialog.getByText(/Lookup-page fallback/)).toBeVisible()
  await dialog.getByLabel("Official record URL").fill("https://www.psacard.com/cert/00001234/psa?_rsc=discard#discard")
  await dialog.getByRole("button", { name: "Use certificate from URL" }).click()
  await expect(dialog.getByRole("alert")).toContainText("selected provider")
  await dialog.getByRole("combobox", { name: "Provider", exact: true }).selectOption("psa")
  await dialog.getByRole("button", { name: "Use certificate from URL" }).click()
  await expect(dialog.getByLabel("Certificate number", { exact: true })).toHaveValue("00001234")
  await expect(dialog.getByLabel("Official record URL")).toHaveValue("")
  const link = dialog.getByRole("link", { name: "View on PSA" })
  await expect(link).toHaveAttribute("href", "https://www.psacard.com/cert/00001234/psa")
  await expect(link).toHaveAttribute("target", "_blank")
  await expect(link).toHaveAttribute("referrerpolicy", "no-referrer")
  await dialog.getByLabel("Official record URL").fill("https://www.psacard.com.evil.test/cert/00001234/psa")
  await dialog.getByRole("button", { name: "Use certificate from URL" }).click()
  await expect(dialog.getByRole("alert")).toBeVisible()
  // Simulate clipboard rejection without leaking cert to any network fallback.
  await page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async () => { throw new Error("Synthetic denied") } } }))
  await dialog.getByRole("button", { name: "Copy certificate number" }).click()
  await expect(dialog.getByRole("status")).toContainText("Select the certificate text")
  expect(outbound).toEqual([])
})

test("rejected, thrown and enqueue-only receipts retain draft and never claim saved", async ({ page }) => {
  const dialog = page.getByRole("dialog", { name: "Edit copy grading" })
  for (const [sink, message] of [["reject", "Synthetic version conflict"], ["queued", "not confirmed persisted"], ["throw", "Synthetic persistence unavailable"]]) {
    await page.getByLabel("Harness sink").selectOption(sink)
    await page.getByRole("button", { name: `Edit ${ace}`, exact: true }).click()
    await dialog.getByLabel("Recorded grade", { exact: true }).fill("9.5")
    await dialog.getByRole("button", { name: "Save grading", exact: true }).click()
    await expect(dialog.getByRole("alert")).toContainText(message)
    await expect(dialog.getByLabel("Recorded grade", { exact: true })).toHaveValue("9.5")
    await expect(page.getByLabel(`Draft ${ace}`)).toContainText('"grade":"9"')
    await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
})

test("all overlay dismissals discard drafts, restore focus, respect safe areas/dock and long text", async ({ page, insets }) => {
  const harness = new Harness(page, insets, false)
  const open = page.getByRole("button", { name: `Edit ${ace}`, exact: true })
  const dialog = page.getByRole("dialog", { name: "Edit copy grading" })
  const before = await page.getByLabel(`Draft ${ace}`).textContent()
  for (const method of ["close", "escape", "back", "backdrop", "swipe", "host"] as const) {
    await open.click()
    await expect(dialog).toBeVisible()
    await dialog.getByLabel("Recorded grade", { exact: true }).fill("SyntheticLongUnbrokenGrade".repeat(18))
    await harness.expectWithinSafeViewport(dialog)
    const close = dialog.getByRole("button", { name: "Close grading editor" })
    await harness.expectHittable(close)
    for (const control of await dialog.locator("input,select,button,a").all()) await harness.expectMinTapTarget(control)
    await harness.expectNoHorizontalOverflow()
    const panel = (await dialog.boundingBox())!, dock = (await page.getByRole("navigation", { name: "Harness dock" }).boundingBox())!
    expect(panel.y + panel.height).toBeLessThanOrEqual(dock.y)
    await harness.expectWithinSafeViewport(dialog.getByRole("button", { name: "Use grading draft" }))
    if (method === "close") await close.click()
    if (method === "escape") await page.keyboard.press("Escape")
    if (method === "back") await page.goBack()
    if (method === "backdrop") await harness.tapBackdrop(dialog)
    if (method === "swipe") await harness.swipeDown(dialog)
    if (method === "host") await page.getByRole("button", { name: "Host tab switch" }).click()
    await expect(dialog).not.toBeVisible()
    await harness.expectScrollUnlocked()
    await expect(open).toBeFocused()
    await expect(page.getByLabel(`Draft ${ace}`)).toHaveText(before!)
    await expect(page).toHaveURL(/\/app\/e2e-harness\/grading$/)
  }
  await page.evaluate(() => document.documentElement.classList.toggle("dark"))
  await open.click()
  await harness.expectWithinSafeViewport(dialog)
  await harness.expectNoHorizontalOverflow()
})
