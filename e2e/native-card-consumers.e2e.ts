import { test, expect, mockBackends, emulateStandalone, Harness } from "./fixtures"
import { inventoryProjectionCatalog } from "../tests/fixtures/inventory-browse"

test.beforeEach(async ({ page, context, standalone, insets, baseURL }) => {
  if (standalone) await emulateStandalone(page, insets)
  await mockBackends(page, context, { signedIn: false, baseURL })
  const cards = inventoryProjectionCatalog.map(c => ({ ...c.card, dexIds: [...c.pokemonIds ?? []], variants: { normal: true } }))
  await page.route("**/app/api/tcgdex-cache**", route => route.fulfill({ json: { cards: cards.filter(c => c.dexIds.includes(Number(new URL(route.request().url()).searchParams.get("pokemonId")))) } }))
  await page.route("**/app/api/tcg-card-search**", route => route.fulfill({ json: { cards } }))
})
const entry = "/app/e2e-harness/native-card-consumers"
// Actual QuickMode/ShowHunt, browser, Search and deal-check components. Read/admission/sink synthetic.
test("Show retains each destination and hands the chosen exact copy/index to the real command planner", async ({ page, insets }) => {
  await page.goto(entry)
  const wants = page.getByRole("region", { name: "Native wanted destinations" })
  await expect(wants).toContainText("3 explicit entries")
  await expect(wants).toContainText("6 physical copies · 4 Unassigned · 1 Unknown exact printing")
  await expect(wants.getByRole("button", { name: "Check price", exact: true })).toHaveCount(3)
  const choice = wants.getByRole("combobox").nth(1)
  await choice.selectOption("copy-00004")
  const use = wants.getByRole("button", { name: "Use this wanted destination" }).nth(1)
  const h = new Harness(page, insets, false)
  await h.expectMinTapTarget(choice)
  await h.expectMinTapTarget(use)
  await use.scrollIntoViewIfNeeded()
  await h.expectWithinSafeViewport(use)
  await h.expectHittable(use)
  await use.click()
  await expect(page.getByLabel("Synthetic draft count")).toHaveText("1")
  const draft = JSON.parse(await page.getByLabel("Synthetic latest draft").textContent() ?? "null")
  expect(draft.intent.request.commands[0]).toMatchObject({ kind: "assign", selection: { kind: "existing", inventoryItemId: "copy-00004", itemVersion: 1 },
    destination: { slot: { id: "alpha-empty-0", version: 1 } }, fulfillWant: { index: 1, expected: { card_id: "synthetic-trainer" } } })
  await expect(wants).toContainText("Draft handed to host, not confirmed saved")
  await expect(wants).toContainText("3 explicit entries")
  await expect(page.getByLabel("Synthetic legacy writes")).toHaveText("0")
  await expect(wants).not.toContainText(/PRIVATE|PSA|CGC|certificate/)
  await h.expectNoHorizontalOverflow()
})

